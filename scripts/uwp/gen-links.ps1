# gen-links.ps1 — generate .cargo/uwp-links.toml with absolute paths (D-05).
#
# Cargo `links` overrides do not resolve relative paths, so this file holds
# machine-specific absolute paths and is regenerated on every machine. It is
# git-ignored and must never be committed. Run after build-deps.ps1.

[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$deps     = Join-Path $repoRoot "out\uwp-deps"
$lib      = Join-Path $deps "lib"
$outFile  = Join-Path $repoRoot ".cargo\uwp-links.toml"

if (-not (Test-Path $lib)) { throw "out/uwp-deps/lib not found. Run scripts\uwp\build-deps.ps1 first." }

# Forward slashes keep the TOML valid (backslashes are escapes in TOML strings).
$depsFwd = $deps -replace '\\', '/'
$libFwd  = $lib  -replace '\\', '/'

# build.rs reads DEP_SDL3_OUT_DIR / DEP_SDL3_TTF_OUT_DIR and appends /include,
# so OUT_DIR must be the prefix that contains include/ (i.e. out/uwp-deps).
$toml = @"
# GENERATED by scripts/uwp/gen-links.ps1 — do not edit, do not commit.
# Cargo `links` overrides for the SDL3 / SDL3_ttf prebuilt UWP DLLs (D-05).
[target.x86_64-uwp-windows-msvc.SDL3]
rustc-link-search = ["native=$libFwd"]
rustc-link-lib = ["SDL3"]
OUT_DIR = "$depsFwd"

[target.x86_64-uwp-windows-msvc.SDL3_ttf]
rustc-link-search = ["native=$libFwd"]
rustc-link-lib = ["SDL3_ttf"]
OUT_DIR = "$depsFwd"
"@

New-Item -ItemType Directory -Force -Path (Split-Path $outFile) | Out-Null
Set-Content -Path $outFile -Value $toml -Encoding UTF8
Write-Host "Wrote $outFile"
Write-Host "Pass it to cargo with:  --config .cargo/uwp-links.toml"
